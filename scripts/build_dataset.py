from __future__ import annotations  # allow forward-referenced type hints on older Python

import json  # write the dataset as JSON
from pathlib import Path  # output file location
from typing import Dict, List  # type hints

from app.taxonomy import route_for  # keep generated routes consistent with the routing map

# NOTE (audit finding, see README "Known Gaps"): this generator produces deterministic, clearly
# synthetic tickets, not the 200+ hand-labelled, class-imbalanced dataset the blueprint requires.
# The checked-in `evaluation/labelled_tickets.json` intentionally ships with only the 6 SEED_ROWS
# below so evaluation numbers are never mistaken for real hand-labelled results. Before reporting
# any evaluation metric as meaningful, replace this dataset with real, hand-verified tickets (see
# blueprint section 8) and record the license/source in the README.

# Hand-written seed tickets: unambiguous, one per taxonomy "shape", used as-is (not templated).
SEED_ROWS: List[Dict[str, str]] = [
    {"ticket_id": "t1", "text": "The site is down and returning 503 errors.", "urgency": "P1", "intent": "outage", "route": "sre-oncall"},
    {"ticket_id": "t2", "text": "I cannot log in after resetting my password.", "urgency": "P2", "intent": "access", "route": "support-triage"},
    {"ticket_id": "t3", "text": "How do I export invoices for last month?", "urgency": "P4", "intent": "howto", "route": "support-howto-queue"},
    {"ticket_id": "t4", "text": "My payment was charged twice and I need a refund.", "urgency": "P3", "intent": "billing", "route": "billing-queue"},
    {"ticket_id": "t5", "text": "The dashboard crashes when I open reports.", "urgency": "P2", "intent": "bug", "route": "eng-triage"},
    {"ticket_id": "t6", "text": "Please add support for SSO on the free plan.", "urgency": "P4", "intent": "feature", "route": "product-ideas-queue"},
]


# Templates cycled to pad the dataset out to `size` rows when a larger (synthetic) set is needed.
TEMPLATES = [
    ("P1", "outage", "The service is down and returning 500 errors."),
    ("P2", "bug", "The export button crashes the page when I click it."),
    ("P2", "access", "I cannot log in because 2FA codes are not accepted."),
    ("P3", "billing", "I was charged incorrectly and need a refund."),
    ("P4", "howto", "How do I invite teammates to the workspace?"),
    ("P4", "feature", "Please add a dark mode option to the product."),
]


def generate_dataset(size: int = 200) -> List[Dict[str, str]]:
    """Return `size` labelled rows: the hand-written seeds first, then template-cycled synthetic
    rows padded out to fill the remainder. Every row's route is derived from the live taxonomy via
    `route_for`, so the generated data can never drift out of sync with `app/taxonomy.py`."""
    rows = list(SEED_ROWS)
    index = 7
    while len(rows) < size:
        urgency, intent, text = TEMPLATES[(len(rows) - len(SEED_ROWS)) % len(TEMPLATES)]
        rows.append(
            {
                "ticket_id": f"t{index}",
                "text": f"{text} #{index}",
                "urgency": urgency,
                "intent": intent,
                "route": route_for(urgency, intent),
            }
        )
        index += 1
    return rows[:size]


def main() -> None:
    """CLI entrypoint: regenerate `evaluation/labelled_tickets.json`. Run explicitly — the
    checked-in file is intentionally NOT auto-regenerated by CI to avoid silently overwriting a
    real hand-labelled dataset with synthetic filler."""
    out_path = Path("evaluation/labelled_tickets.json")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(generate_dataset(), indent=2), encoding="utf-8")
    print(f"Wrote {out_path}")


if __name__ == "__main__":  # pragma: no cover
    main()
